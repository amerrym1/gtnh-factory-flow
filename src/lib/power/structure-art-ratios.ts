/** The width over the height of a face's picture: a structure render's own, 1 for anything else (an item icon). */
export function artRatio(url: string | undefined): number {
  const id = url?.match(/\/power-art\/([^/]+)\.png$/)?.[1];
  return (id !== undefined ? STRUCTURE_ART_RATIOS[id] : undefined) ?? 1;
}
